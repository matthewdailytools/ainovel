def request_payload(domain, artifact_id, data):
    candidate = domain.artifact(artifact_id)
    return {
        **data.model_dump(),
        "source_candidate_id": artifact_id,
        "novel_id": candidate["novel_id"],
        "branch_id": candidate["branch_id"],
        "chapter_id": candidate["chapter_id"],
        "base_revision": candidate["base_revision"],
    }


def query_request(domain, artifact_id, client_request_id, kind):
    rows = domain.db.all("SELECT task_id FROM task_requests WHERE key=?", (client_request_id,))
    if not rows:
        raise DomainError("not_found", "未找到该提交标识的任务；结果未知时保留原标识继续查证。", 404)
    task = domain.task(rows[0]["task_id"])
    if task["kind"] != kind or task["payload"].get("source_candidate_id") != artifact_id:
        raise DomainError("idempotency", "该提交标识属于不同目标或操作。", 409)
    return task


def register_routes(app, domain, budget, provider_ready):
    @app.get("/api/artifacts/{artifact_id}/source-interpretation-correction-preview")
    def correction_preview(artifact_id: str):
        return preview(domain, artifact_id)

    @app.post("/api/artifacts/{artifact_id}/source-interpretation-corrections", status_code=202)
    def create_correction(artifact_id: str, data: CorrectionInput):
        payload = versioned_payload(domain, request_payload(domain, artifact_id, data))
        previous = domain.find_request(KIND, payload)
        if previous:
            return previous
        provider_ready(data.account)
        return domain.queue(KIND, payload)

    @app.get("/api/artifacts/{artifact_id}/source-interpretation-corrections/{client_request_id}")
    def correction_request(artifact_id: str, client_request_id: str):
        return query_request(domain, artifact_id, client_request_id, KIND)
