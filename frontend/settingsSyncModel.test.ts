import { createHash } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import {
  inspectSettingsDraft,
  prepareSettingsVersion,
  settingCategories,
  validateSettingsSyncObject,
  validateSettingsVersionSources,
} from './settingsSyncModel'

function fixture(includeMissing = false) {
  const north = {
    id: 'north',
    title: 'ẞ 遗铃',
    detail: '铃\n响',
    links: includeMissing ? ['south', 'missing'] : ['south'],
    setting_policy: { strength: 'hard', scope: '北城', exceptions: '😀' },
  }
  const south = {
    id: 'south',
    title: 'SS 遗铃',
    detail: '铃不响',
    setting_policy: { strength: 'soft', scope: '南城', exceptions: '守夜人' },
  }
  return {
    id: 'setting-two',
    parent_id: 'setting-one',
    project_version_id: 'project-two',
    categories: settingCategories.map(([id, title]) => ({
      id,
      title,
      items: id === 'world' ? [north, south] : [],
    })),
    origins: {
      north: { origin: 'ai', project_version_id: 'project-one' },
      south: { origin: 'author' },
    },
  }
}

describe('正式设定离线模型', () => {
  it('与 Python 生成相同的有证据发现编号，保留无效链接双方位置', async () => {
    const input = fixture(true)
    const inspection = await inspectSettingsDraft(input.categories, input.origins, input.project_version_id)
    // Generated by ainovel.conception.setting_findings on this exact fixture.
    expect(inspection.findings.map(({ kind, id }) => [kind, id])).toEqual([
      ['same_name', '9aa2e2d7d2853c348b154e70003d14eb27f07a260c84893790e972a20fb88097'],
      ['policy_link', '666ce9b8bc5805f128004663fe0e6c64c88a12193c00b66dccb1400a331f4281'],
      ['missing_link', 'd1ac2e76ce09b9f28c7254ccbf182eea5ec6015ca6e3ba76bb3187fd03c08a57'],
    ])
    expect(inspection.findings[2].locations).toMatchObject([
      { category_id: 'world', item_id: 'north', item_number: 1, link_number: 2 },
      { category_id: null, item_id: 'missing', item_number: null },
    ])
    await expect(
      prepareSettingsVersion({
        ...input,
        reconciled_project_items: ['north'],
        reviewed_setting_findings: inspection.findings.map(({ id }) => id),
      }),
    ).rejects.toThrow('无效的条目关联')
  })

  it('只接受当前证据和立项逐项留审，拒绝跨范围与额外字段', async () => {
    const input = fixture()
    const { findings, projectImpacts } = await inspectSettingsDraft(
      input.categories,
      input.origins,
      input.project_version_id,
    )
    expect(projectImpacts).toEqual(['north'])
    const confirmed = {
      ...input,
      reconciled_project_items: ['north'],
      reviewed_setting_findings: findings.map(({ id }) => id),
    }
    await expect(prepareSettingsVersion(input)).rejects.toThrow('立项变更')
    await expect(
      prepareSettingsVersion({ ...confirmed, reviewed_setting_findings: ['old'] }),
    ).rejects.toThrow('设定冲突')
    const wire = {
      format: 'ainovel-manuscript-sync/1',
      kind: 'settings-version',
      branch_id: 'work',
      version: confirmed,
    }
    await expect(
      validateSettingsSyncObject('work', 'settings-version:setting-two', wire),
    ).resolves.toMatchObject({
      version: { id: 'setting-two', parent_id: 'setting-one', origins: { north: { origin: 'ai' } } },
    })
    await expect(validateSettingsSyncObject('other', 'settings-version:setting-two', wire)).rejects.toThrow(
      '工作版本',
    )
    await expect(
      prepareSettingsVersion({
        ...confirmed,
        origins: { ...confirmed.origins, unrelated: { origin: 'author' } },
      }),
    ).rejects.toThrow('每条设定需要原始来源')
  })

  it('锁定同作品的项目、前版本及 UTF-16 正文选区', async () => {
    const input = fixture()
    const inspected = await inspectSettingsDraft(input.categories, input.origins, input.project_version_id)
    const evidence = {
      chapter_id: 'chapter',
      revision_id: 'revision',
      start: 1,
      end: 3,
      quote_sha256: createHash('sha256').update('😀').digest('hex'),
    }
    const confirmed = await prepareSettingsVersion({
      ...input,
      origins: { ...input.origins, north: { ...input.origins.north, evidence } },
      reconciled_project_items: inspected.projectImpacts,
      reviewed_setting_findings: inspected.findings.map(({ id }) => id),
    })
    const lookup = {
      project: (id: string) => ['project-one', 'project-two'].includes(id),
      settings: (id: string) => id === 'setting-one',
      revision: () => ({ id: 'revision', chapter_id: 'chapter', content: '铃😀响' }),
    }
    await expect(validateSettingsVersionSources(confirmed, lookup)).resolves.toBeUndefined()
    await expect(
      validateSettingsVersionSources(confirmed, { ...lookup, settings: () => false }),
    ).rejects.toThrow('父版本')
    await expect(
      validateSettingsVersionSources(confirmed, { ...lookup, revision: () => undefined }),
    ).rejects.toThrow('准确正文修订')
    confirmed.origins.north.evidence = { ...evidence, end: 2 }
    await expect(validateSettingsVersionSources(confirmed, lookup)).rejects.toThrow('正文选区')
  })
})
