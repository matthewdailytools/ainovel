import { createHash } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import {
  buildStoryVersion,
  captureStoryEvidence,
  orderStoryVersions,
  validateStoryHeadSelection,
  validateStoryHistory,
  validateStorySyncObject,
  validateStoryVersionSources,
} from './storySyncModel'

const branch = 'branch-a'
const content = '铃😀响'
const located = {
  id: 'remote-page',
  chapter_id: 'chapter',
  content,
  sha256: createHash('sha256').update(content).digest('hex'),
}

async function promiseVersions() {
  const record = { kind: 'promise', title: '双笔铸记😀', notes: '先埋后收\n' }
  const base = { record_id: 'bell-clue', archived: false, dependencies: {} }
  const planned = await buildStoryVersion(branch, {
    ...base,
    parent_id: null,
    record: { ...record, stages: [{ status: 'planned' }] },
    evidence: { record: [], stages: [[]] },
  })
  const proof = await captureStoryEvidence(located, 1, 3)
  const resolved = await buildStoryVersion(branch, {
    ...base,
    parent_id: planned.id,
    record: { ...record, stages: [{ status: 'planned' }, { status: 'resolved', note: '金铃打开' }] },
    evidence: { stages: [[], [proof]] },
  })
  return { planned, resolved, proof }
}

describe('离线正式故事记录协议', () => {
  it('与 Python 计算同一 SHA-256，保留阶段证据且拒绝篡改和跨工作版本', async () => {
    const { planned, resolved } = await promiseVersions()
    // Generated by backend/ainovel/story_sync.py::story_version_id from this fixture.
    expect(planned.id).toBe('65dbdf8730be9526f00b784030f5f4c63100970dfe20ac328721397e756255ce')
    expect(resolved.id).toBe('59ad2d01f4cbfa0c5b5926ab71369dcaa0d07db3fef2d510c782c531bee2d605')
    const wrapper = {
      format: 'ainovel-manuscript-sync/1',
      kind: 'story-version',
      branch_id: branch,
      version: resolved,
    }
    await expect(
      validateStorySyncObject(branch, `story-version:${resolved.id}`, wrapper),
    ).resolves.toMatchObject({ version: resolved })
    await expect(
      validateStorySyncObject('other', `story-version:${resolved.id}`, { ...wrapper, branch_id: 'other' }),
    ).rejects.toThrow('版本哈希')
    await expect(
      validateStorySyncObject(branch, `story-version:${resolved.id}`, {
        ...wrapper,
        version: { ...resolved, record: { ...resolved.record, notes: '未授权改写' } },
      }),
    ).rejects.toThrow('版本哈希')
    await expect(captureStoryEvidence(located, 1, 2)).rejects.toThrow('不能拆开')
    await expect(
      buildStoryVersion(branch, {
        parent_id: planned.id,
        record_id: planned.record_id,
        archived: false,
        record: resolved.record,
        dependencies: {},
        evidence: { stages: [[], []] },
      }),
    ).rejects.toThrow('缺少原文证据')
  })

  it('先接原父版本和原稿，归档或历史同文需要准确绑定', async () => {
    const { planned, resolved } = await promiseVersions()
    expect(
      orderStoryVersions(
        new Map([
          [resolved.id, resolved],
          [planned.id, planned],
        ]),
      ),
    ).toEqual([planned, resolved])
    const sources = {
      story: (id: string) => (id === planned.id ? planned : undefined),
      revision: (id: string) => (id === located.id ? located : undefined),
    }
    await expect(validateStoryVersionSources(resolved, sources)).resolves.toBeUndefined()
    await expect(
      validateStoryVersionSources(resolved, { ...sources, story: () => undefined }),
    ).rejects.toThrow('上一个版本')
    await expect(
      validateStoryVersionSources(resolved, { ...sources, revision: () => undefined }),
    ).rejects.toThrow('原始章稿')
    const nativePage = { ...located, id: 'native-page' }
    const archive = {
      adopted_heads: { 'bell-clue': resolved.id },
      versions: [resolved, planned],
      source_devices: { [resolved.id]: '桌面-a' },
      native_history: {
        'bell-clue': [
          {
            revision: 0,
            version_id: planned.id,
            created: 1,
            dependencies: {},
            evidence: { record: [], stages: [[]] },
          },
          {
            revision: 1,
            version_id: resolved.id,
            created: 2,
            dependencies: {},
            evidence: { record: [], stages: [[], [nativePage.id]] },
          },
        ],
      },
    }
    const revisions = {
      original: new Map([[located.id, located]]),
      native: new Map([[nativePage.id, nativePage]]),
    }
    await expect(validateStoryHistory(branch, archive, revisions)).resolves.toEqual(archive)
    await expect(
      validateStoryHistory(branch, archive, {
        ...revisions,
        native: new Map([[nativePage.id, { ...nativePage, sha256: '0'.repeat(64) }]]),
      }),
    ).rejects.toThrow('同全文')
    const cachedOnly = { ...archive, adopted_heads: {}, native_history: {} }
    await expect(validateStoryHistory(branch, cachedOnly, revisions)).resolves.toEqual(cachedOnly)
  })

  it('挂载关系只采用准确的角色和实际事件，当前头不会形成循环', async () => {
    const version = async (
      record_id: string,
      record: object,
      dependencies: Record<string, string> = {},
      parent_id: string | null = null,
    ) =>
      buildStoryVersion(branch, { record_id, parent_id, record, dependencies, archived: false, evidence: {} })
    const first = await version('first', { kind: 'character', title: '阿芹' })
    const second = await version(
      'second',
      { kind: 'character', title: '夜巡人', depends_on: ['first'] },
      { first: first.id },
    )
    const cycle = await version(
      'first',
      { kind: 'character', title: '阿芹', depends_on: ['second'] },
      { second: second.id },
      first.id,
    )
    expect(() =>
      validateStoryHeadSelection(
        cycle,
        new Map([
          ['first', first],
          ['second', second],
        ]),
      ),
    ).toThrow('形成循环')
    const planned = await version('event', { kind: 'event', title: '渡口相认' })
    const proof = await captureStoryEvidence(located, 1, 3)
    const relationship = await buildStoryVersion(branch, {
      parent_id: null,
      record_id: 'relation',
      archived: false,
      record: {
        kind: 'relationship',
        title: '识别来历',
        from_id: 'first',
        to_id: 'second',
        event_id: 'event',
        relation: '故交',
        truth: 'actual',
      },
      evidence: { record: [proof] },
      dependencies: { first: first.id, second: second.id, event: planned.id },
    })
    const sources = new Map([first, second, planned].map((entry) => [entry.id, entry]))
    await expect(
      validateStoryVersionSources(relationship, {
        story: (id) => sources.get(id),
        revision: () => located,
      }),
    ).rejects.toThrow('已发生的关联事件')
    expect(() =>
      validateStoryHeadSelection(
        relationship,
        new Map([
          ['first', first],
          ['second', second],
        ]),
      ),
    ).toThrow('尚未采用')
  })
})
