"""Freeze the desktop body count character classes for offline browsers."""

import argparse
from itertools import groupby
from pathlib import Path
import unicodedata

from ainovel.workflow_inspection import COUNT_VERSION, body_chars


def js_ranges(name, predicate):
    def escape(codepoint):
        return rf"\\u{{{codepoint:x}}}"

    entries = []
    for accepted, points in groupby(range(0x110000), key=lambda point: predicate(chr(point))):
        if not accepted:
            continue
        first = next(points)
        last = max(points, default=first)
        entries.append(escape(first) + ("-" + escape(last) if last != first else ""))
    rows = ["  '" + "".join(entries[start : start + 4]) + "'," for start in range(0, len(entries), 4)]
    return "\n".join([f"export const {name} = [", *rows, "].join('')"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if unicodedata.unidata_version != "16.0.0":
        raise SystemExit(f"{COUNT_VERSION} uses the desktop Python Unicode 16.0.0 data.")
    output = (
        "\n\n".join(
            (
                "// Generated by uv run python scripts/generate_body_count_unicode.py (Unicode 16.0.0).",
                f"export const bodyCountMethod =\n  {COUNT_VERSION!r}",
                # Keep the character off the start of a Markdown line (a literal ">" can count).
                js_ranges("bodyCountCharacters", lambda char: body_chars("甲" + char) == 2),
                js_ranges("bodyCountDecimals", str.isdecimal),
                js_ranges("bodyCountWhitespace", str.isspace),
            )
        )
        + "\n"
    )
    target = Path(__file__).resolve().parents[1] / "frontend/bodyCountUnicode16.ts"
    if args.check:
        if target.read_text(encoding="utf-8") != output:
            raise SystemExit("Offline body count classes are out of date.")
    else:
        target.write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
